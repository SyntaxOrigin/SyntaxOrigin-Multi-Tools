let LANG = DEFAULT_LANG;

function t(key) {
    const d = I18N[LANG];
    if (d && key in d) return d[key];
    const en = I18N.en;
    return (en && key in en) ? en[key] : key;
}

function tpl(key, vars) {
    return t(key).replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] != null) ? vars[k] : "");
}

function normalizeLang(c) {
    c = (c || "").toLowerCase().replace("_", "-").split("-")[0];
    if (c === "id") return "ms";
    if (c && I18N[c]) return c;
    return "";
}

function setLang(code, remember) {
    if (!I18N[code]) code = DEFAULT_LANG;
    LANG = code;
    const rtl = !!RTL_LANGS[code];
    document.documentElement.setAttribute("dir", rtl ? "rtl" : "ltr");
    document.documentElement.setAttribute("lang", code);
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        el.innerHTML = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
        el.placeholder = t(el.dataset.i18nPh);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        el.title = t(el.dataset.i18nTitle);
    });
    if (remember !== false) {
        try {
            localStorage.setItem("smt_lang", code);
        } catch (e) { /* yok say */ }
    }
    try {
        if (window.go && window.go.main && window.go.main.App && window.go.main.App.SetLanguage) {
            window.go.main.App.SetLanguage(code).catch(() => { /* yok say */ });
        }
    } catch (e) { /* yok say */ }
    if (typeof applyDynamicI18n === "function") applyDynamicI18n();
}

/* Dil kutusunu doldur ve değişimi bağla. Giriş dili: kullanıcı seçimi →
 * sistem dili → varsayılan (İngilizce). */
async function initLangSelect() {
    const sel = document.getElementById("langSel");
    if (!sel) return;
    sel.innerHTML = "";
    LANGS.forEach((l) => {
        const o = document.createElement("option");
        o.value = l.code;
        o.textContent = l.name;
        sel.appendChild(o);
    });

    let code = "";
    try {
        code = normalizeLang(localStorage.getItem("smt_lang"));
    } catch (e) { /* yok say */ }
    if (!code) {
        try {
            code = normalizeLang(await window.go.main.App.SystemLanguage());
        } catch (e) { /* yok say */ }
    }
    if (!code) code = normalizeLang(navigator.language);
    if (!code) code = DEFAULT_LANG;

    sel.value = code;
    sel.addEventListener("change", () => setLang(sel.value));
    setLang(code, false);
}